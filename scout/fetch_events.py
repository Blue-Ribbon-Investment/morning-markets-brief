#!/usr/bin/env python3
"""Best-effort: pull conference / event pages from major Indian research
centres and dump their readable text into one file for Claude to mine.

Claude is the intelligence layer — it reads this file plus does web search to
find, verify and de-duplicate academic events. This fetcher is a recall boost:
it hands Claude the raw text of known calendars so it doesn't rely on search
alone. Every source is optional; failures just mean Claude falls back on search.

Usage: python -I -X utf8 scout/fetch_events.py <month_label> <outdir>
"""
import sys, os, re, json, datetime
import requests

MONTH_LABEL = sys.argv[1]
OUT = sys.argv[2]
os.makedirs(OUT, exist_ok=True)

HEADERS = {'User-Agent': ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) '
      'AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36')}
TIMEOUT = 15

# (name, URL, city) — institute event pages in the three requested cities.
# Best-effort: any broken path just logs a warning, and Claude falls back to
# web search to fill the gaps. Keep this to pages that actually resolve —
# dead links here just add noise to the raw dump. Verify a URL before adding it.
SOURCES = [
    # Mumbai
    ('IIT Bombay — Events',     'https://www.iitb.ac.in/events/',        'Mumbai'),
    ('Tata Institute of Fundamental Research',
                                    'https://www.tifr.res.in/',          'Mumbai'),
    # Ahmedabad and Pune are covered by Claude's web search on every run;
    # add a direct event-page URL here only when you find one that resolves.
]

# Lines containing these are worth keeping (a conference/seminar callout, etc.)
KEEP = re.compile(
    r'(conference|workshop|seminar|symposia?|summit|webinar|conclave|'
    r'call for papers|CfP|keynote|plenary|research|publica|journal|'
    r'thesis|dissertation|PhD|abstract|upcoming|schedule|deadline)',
    re.IGNORECASE)

def html_to_lines(html):
    text = re.sub(r'<script[^>]*>.*?</script>', ' ', html, flags=re.DOTALL|re.IGNORECASE)
    text = re.sub(r'<style[^>]*>.*?</style>', ' ', text, flags=re.DOTALL|re.IGNORECASE)
    # break block elements into lines
    text = re.sub(r'</(p|div|li|tr|h[1-6]|section|article|td|header|footer)>', '\n', text, flags=re.IGNORECASE)
    text = re.sub(r'<[^>]+>', ' ', text)
    text = re.sub(r'&amp;', '&', text)
    text = re.sub(r'&nbsp;|&#160;', ' ', text)
    text = re.sub(r'&#(\d+);', lambda m: chr(int(m.group(1))), text)
    # collapse runs of spaces/tabs but keep our line breaks
    text = re.sub(r'[ \t]+', ' ', text)
    text = re.sub(r'\n\s*', '\n', text)
    return [l.strip() for l in text.splitlines() if l.strip()]

def fetch(name, url, city):
    out = []
    try:
        r = requests.get(url, headers=HEADERS, timeout=TIMEOUT)
        r.raise_for_status()
        lines = html_to_lines(r.text)
    except Exception as e:
        out.append(f'### {name} ({city}) — {url}')
        out.append(f'[fetch failed: {e}]')
        out.append('')
        return out

    out.append(f'### {name} ({city}) — {url}')
    kept = [l for l in lines if KEEP.search(l)]
    # If the page is short, keep it all; otherwise keep keyword lines with a bit of context.
    if len(lines) <= 60:
        kept = lines
    for l in kept:
        if len(l) > 300:
            l = l[:300] + '…'
        out.append(l)
    out.append('')
    return out

result = [f'Academic event source dump for {MONTH_LABEL}. '
          'Generated by fetch_events.py. Each "###" block is one source.']
result.append('')
for name, url, city in SOURCES:
    print(f'Fetching: {name}')
    block = fetch(name, url, city)
    result.extend(block)

out_path = os.path.join(OUT, 'raw_events.txt')
with open(out_path, 'w', encoding='utf-8') as f:
    f.write('\n'.join(result))
print(f'Wrote {len(result)} lines to {out_path}')
